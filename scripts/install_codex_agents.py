#!/usr/bin/env python3
"""Generates native Codex CLI multi-agent TOML configs with live web search on Kali Linux.

Reads assets/codex-agents-manifest.json and writes:
  - <target>/.codex/config.toml (with bare top-level web_search above all [tables])
  - <target>/.codex/agents/<agent_name>.toml for all 13 specialists
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def toml_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def render_agent_toml(agent: dict) -> str:
    nicknames = ", ".join(f'"{toml_escape(n)}"' for n in agent.get("nickname_candidates", []))
    instructions = agent["developer_instructions"].replace('"""', '\\"\\"\\"')
    return (
        f'name = "{toml_escape(agent["name"])}"\n'
        f'description = "{toml_escape(agent["description"])}"\n'
        f'model = "{toml_escape(agent["model"])}"\n'
        f'model_reasoning_effort = "{toml_escape(agent["model_reasoning_effort"])}"\n'
        f'sandbox_mode = "{toml_escape(agent["sandbox_mode"])}"\n'
        f'nickname_candidates = [{nicknames}]\n\n'
        f'developer_instructions = """\n{instructions}\n"""\n'
    )


def render_config_toml(cfg: dict, web_search_override: str | None = None) -> str:
    web_search_mode = web_search_override or cfg.get("web_search", "live")
    context_size = cfg.get("web_search_context_size", "high")
    multi = "true" if cfg.get("multi_agent", True) else "false"
    max_threads = int(cfg.get("max_threads", 6))
    max_depth = int(cfg.get("max_depth", 1))

    # IMPORTANT: In Codex config.toml, web_search is a bare top-level key and MUST
    # appear before any [section] header so TOML does not bind it to a table.
    return (
        "# Generated by cyber-command-hive-apex/scripts/install_codex_agents.py\n"
        "# Top-level keys MUST stay above [section] headers.\n"
        f'web_search = "{toml_escape(web_search_mode)}"\n\n'
        "[tools.web_search]\n"
        f'context_size = "{toml_escape(context_size)}"\n\n'
        "[features]\n"
        f"multi_agent = {multi}\n\n"
        "[agents]\n"
        f"max_threads = {max_threads}\n"
        f"max_depth = {max_depth}\n"
    )


def main() -> int:
    skill_root = Path(__file__).resolve().parent.parent
    manifest_path = skill_root / "assets" / "codex-agents-manifest.json"

    parser = argparse.ArgumentParser(
        description="Install Cyber Command Hive Apex (13 Codex subagents + live web search config)."
    )
    parser.add_argument(
        "--scope",
        choices=("project", "global"),
        default="project",
        help="Install into ./.codex/ (project) or ~/.codex/ (global).",
    )
    parser.add_argument(
        "--target-dir",
        type=Path,
        default=None,
        help="Optional explicit base directory (overrides --scope).",
    )
    parser.add_argument(
        "--web-search",
        choices=("live", "cached", "indexed", "disabled"),
        default=None,
        help="Override Codex web_search mode in config.toml (default: live).",
    )
    parser.add_argument(
        "--skip-config",
        action="store_true",
        help="Do not overwrite config.toml; only write agents/*.toml.",
    )
    args = parser.parse_args()

    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if args.target_dir is not None:
        codex_dir = args.target_dir / ".codex"
    elif args.scope == "global":
        codex_dir = Path.home() / ".codex"
    else:
        codex_dir = Path.cwd() / ".codex"

    agents_dir = codex_dir / "agents"
    agents_dir.mkdir(parents=True, exist_ok=True)

    written: list[str] = []
    if not args.skip_config:
        cfg_file = codex_dir / "config.toml"
        cfg_file.write_text(render_config_toml(manifest["codex_config"], args.web_search), encoding="utf-8")
        written.append(str(cfg_file))

    for agent in manifest["agents"]:
        agent_file = agents_dir / f'{agent["name"]}.toml'
        agent_file.write_text(render_agent_toml(agent), encoding="utf-8")
        written.append(str(agent_file))

    print(f"Installed {len(manifest['agents'])} Codex subagents into {agents_dir}")
    for path in written:
        print(f"  - {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
